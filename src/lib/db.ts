/** Advisory lock keys. Any fixed numbers work, as long as nothing else uses them. */
const SCHEMA_LOCK = 7_340_001;
const WRITE_LOCK = 7_340_002;

export const now = (): string => new Date().toISOString();

function createPool(): pg.Pool {
  if (!config.DATABASE_URL || config.DATABASE_URL.includes('YOUR_')) {
    throw new Error(process.env.VERCEL
      ? 'DATABASE_URL is not set. Add it in Vercel: Settings > Environment Variables (Production), then redeploy.'
      : 'DATABASE_URL in .env is not set up yet. Run `npm run db:password`, then restart the app.');
  }
  const host = new URL(config.DATABASE_URL).hostname;
  const local = host === 'localhost' || host === '127.0.0.1' || host === '::1';
  return new pg.Pool({
    connectionString: config.DATABASE_URL,
    max: config.DATABASE_POOL_MAX,
    // Opening a connection costs several round trips (and seconds when the database is far
    // away), so keep idle ones open for a while instead of pg's default of 10 seconds.
    idleTimeoutMillis: 5 * 60 * 1000,
    keepAlive: true,
    // Supabase's certificate is not signed by a CA that Node trusts out of the box,
    // so the connection is encrypted without verifying the certificate.
    ssl: local ? undefined : { rejectUnauthorized: false },
  });
}

// One pool per server process. Kept on globalThis so that hot reloads
// in development reuse it instead of opening new connections each time.
const holder = globalThis as unknown as { __packagingPool?: pg.Pool };
// Module state, so it resets on every hot reload and new code re-applies the schema once.
let ready: Promise<void> | null = null;

function pool(): pg.Pool {
  return (holder.__packagingPool ??= createPool());
}

// A fingerprint of SCHEMA, recorded once it is applied. Any change to SCHEMA changes it.
const SCHEMA_HASH = crypto.createHash('sha256').update(SCHEMA).digest('hex');

/**
 * Create missing tables. Usually the recorded fingerprint matches and this is
 * one quick lookup; the full schema only runs after SCHEMA changes (it takes
 * table locks, so running it on every server start would slow everyone down).
 * Two server processes starting together take turns.
 */
async function migrate(): Promise<void> {
  const meta = await pool().query<{ found: boolean }>("SELECT to_regclass('public.app_meta') IS NOT NULL AS found");
  if (meta.rows[0].found) {
    const applied = await pool().query<{ value: string }>("SELECT value FROM app_meta WHERE key = 'schema'");
    if (applied.rows[0]?.value === SCHEMA_HASH) return;
  }
  const client = await pool().connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock($1)', [SCHEMA_LOCK]);
    await client.query(SCHEMA);
    await client.query(
      `INSERT INTO app_meta (key, value) VALUES ('schema', $1) ON CONFLICT (key) DO UPDATE SET value = excluded.value`,
      [SCHEMA_HASH]);
    await client.query('COMMIT');
  } catch (err) {
    await client.query('ROLLBACK').catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

function ensureReady(): Promise<void> {
  // A failed attempt is forgotten so the next request tries again.
  ready ??= migrate().catch((err) => { ready = null; throw err; });
  return ready;
}

/** The connection of the transaction this code is running inside, if any. */
const txClient = new AsyncLocalStorage<pg.PoolClient>();

type Param = string | number | bigint | boolean | Buffer | null;

// The app writes ? placeholders (as it did with SQLite); Postgres wants $1, $2, ...
// No query has a ? inside a quoted string, so a plain replace is enough.
const converted = new Map<string, string>();
function toPg(sql: string): string {
  let text = converted.get(sql);
  if (text === undefined) {
    let n = 0;
    text = sql.replace(/\?/g, () => `$${++n}`);
    converted.set(sql, text);
  }
  return text;
}

async function query<T extends pg.QueryResultRow>(sql: string, params: Param[]): Promise<pg.QueryResult<T>> {
  await ensureReady();
  return (txClient.getStore() ?? pool()).query<T>(toPg(sql), params);
}

export async function get<T>(sql: string, ...params: Param[]): Promise<T | undefined> {
  return (await query(sql, params)).rows[0] as T | undefined;
}

export async function all<T>(sql: string, ...params: Param[]): Promise<T[]> {
  return (await query(sql, params)).rows as T[];
}

/** Run a statement that returns no rows. `changes` is how many rows it touched. */
export async function run(sql: string, ...params: Param[]): Promise<{ changes: number }> {
  return { changes: (await query(sql, params)).rowCount ?? 0 };
}

/** Run an INSERT and return the id of the new row. */
export async function insert(sql: string, ...params: Param[]): Promise<number> {
  return (await query<{ id: number }>(`${sql} RETURNING id`, params)).rows[0].id;
}

export const inTransaction = (): boolean => txClient.getStore() !== undefined;

/**
 * Run fn inside one database transaction. Either everything fn does is saved
 * or, if it throws, nothing is. Every transaction first takes the same lock,
 * so two requests can never interleave their stock updates (what SQLite's
 * BEGIN IMMEDIATE did). Every query fn makes, however deep, uses this
 * transaction's connection.
 */
export async function tx<T>(fn: () => Promise<T>): Promise<T> {
  if (inTransaction()) return fn();
  await ensureReady();
  const client = await pool().connect();
  let broken: Error | undefined;
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock($1)', [WRITE_LOCK]);
    const result = await txClient.run(client, fn);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    // If even the rollback fails the connection is unusable; release(err) closes it.
    await client.query('ROLLBACK').catch((e: Error) => { broken = e; });
    throw err;
  } finally {
    client.release(broken);
  }
}

/** Close every connection, for scripts and tests that need the process to exit. */
export async function close(): Promise<void> {
  const p = holder.__packagingPool;
  holder.__packagingPool = undefined;
  ready = null;
  await p?.end();
}

export async function warehouseId(): Promise<number> {
  return (await get<{ id: number }>("SELECT id FROM locations WHERE type = 'warehouse'"))!.id;
}
